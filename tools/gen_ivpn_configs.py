#!/usr/bin/env python3
"""Generate one IP-based .ovpn file per IVPN server.

IVPN's stock configs do not fit this project as downloaded, for two reasons:

  * Their remotes are hostnames, so OpenVPN needs working DNS BEFORE the tunnel
    exists. If OpenVPN is SIGKILLed its --down hook never runs, /etc/resolv.conf
    keeps pointing at IVPN's in-tunnel resolver, and every later connect fails
    until the container is recreated. Proton's files use IPs, so this never
    came up there.
  * Many files list several servers with `remote-random`, but the scorer assumes
    one .ovpn file is one exit server. One bad server would eject its whole city.

Each output file therefore has exactly one `remote <ip> <port>`. An IP that goes
stale fails like any other dead endpoint and is ejected until you re-run this.

Python 3 standard library only. The result is baked into the image at build time:

    tools/gen_ivpn_configs.py --country CH,SE,DE
    docker compose -f docker-compose.ivpn.yml up -d --build
"""

import argparse
import http.client
import io
import ipaddress
import json
import os
import re
import sys
import tempfile
import unicodedata
import urllib.parse
import urllib.request
import zipfile
import zlib

SERVERS_URL = "https://api.ivpn.net/v5/servers.json"
CONFIG_URL = "https://api.ivpn.net/v5/config/ivpn-openvpn-config.zip"
DEFAULT_PORTS = {"udp": 2049, "tcp": 443}
DEFAULT_OUTPUT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "ovpn_configs_ivpn"
)
MAX_DOWNLOAD_BYTES = 10 * 1024 * 1024
# Identifies our files, so pruning can never delete a config we did not write.
MARKER = "# Generated by tools/gen_ivpn_configs.py"
# The fleet size the scoring defaults are tuned for (see .env.example.txt) is
# ~8; at a daily rotation, a much larger fleet takes months to visit once.
LARGE_FLEET = 20

# An allowlist, not a denylist: these files run under OpenVPN as root and this
# script fetches them automatically, so a directive it has never seen (`up`,
# `plugin`, `tls-verify`, ...) stops the run instead of reaching the image. If
# IVPN adds something harmless, review it and add it here.
ALLOWED_DIRECTIVES = frozenset(
    """
    auth auth-user-pass cipher client comp-lzo data-ciphers data-ciphers-fallback
    dev explicit-exit-notify key-direction mssfix mute mute-replay-warnings nobind
    persist-key persist-remote-ip persist-tun proto pull remote remote-cert-tls
    remote-random reneg-sec resolv-retry tls-cipher tls-client tls-version-min
    tun-mtu verb verify-x509-name
    """.split()
)
ALLOWED_BLOCKS = frozenset({"ca", "tls-auth", "tls-crypt"})

BLOCK_RE = re.compile(r"^<(/?)([A-Za-z0-9-]+)>$")
# What a PEM or static-key body may contain. OpenVPN ends an inline block at any
# line that merely STARTS with the closing tag, so `</ca> x` closes it there but
# not here, and whatever follows would skip the allowlist. Nothing in this set
# can contain `<`, which also rules out a tag at OpenVPN's 256-byte read boundary.
BLOCK_BODY_RE = re.compile(r"[A-Za-z0-9+/=]*|-----(?:BEGIN|END) [A-Za-z0-9 ]+-----")
HOSTNAME_RE = re.compile(r"^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$")


class GenerationError(Exception):
    """A problem that must stop the run and leave existing output untouched."""


def warn(message):
    print(f"WARNING: {message}", file=sys.stderr)


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": "gen_ivpn_configs/1"})
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            body = response.read(MAX_DOWNLOAD_BYTES + 1)
    except (OSError, http.client.HTTPException) as exc:
        raise GenerationError(f"could not download {url}: {exc}") from exc
    if len(body) > MAX_DOWNLOAD_BYTES:
        raise GenerationError(f"{url} is larger than {MAX_DOWNLOAD_BYTES} bytes")
    return body


def check_port(servers, proto, port):
    """Reject a port IVPN does not serve. The config API echoes any value back,
    including 99999, so an invalid port would otherwise fail only at connect."""
    for entry in servers.get("config", {}).get("ports", {}).get("openvpn", []):
        if str(entry.get("type", "")).lower() != proto:
            continue
        span = entry.get("range")
        if entry.get("port") == port or (span and span["min"] <= port <= span["max"]):
            return
    raise GenerationError(f"IVPN does not list {proto.upper()} port {port} for OpenVPN")


def index_hosts(servers):
    """Map each hostname to (ipv4, country code), skipping unusable addresses.

    IPv4 only: the supervisor filters pushed IPv6 and its kill switch checks an
    IPv4 route. Non-global addresses are never a real VPN gateway.
    """
    hosts = {}
    for gateway in servers.get("openvpn", []):
        for host in gateway.get("hosts", []):
            name, address = host.get("dns_name") or host.get("hostname"), host.get("host")
            try:
                ip = ipaddress.ip_address(address)
            except ValueError:
                ip = None
            if not name or ip is None or ip.version != 4 or not ip.is_global:
                warn(f"skipping server with unusable address: {name!r} -> {address!r}")
                continue
            hosts[name.lower()] = (str(ip), str(gateway.get("country_code", "")).upper())
    return hosts


def parse_template(source, text):
    """Validate one stock config. Returns (lines without remotes, hostnames, slot),
    where slot is the index the single replacement `remote` line goes in at."""
    kept, remotes, slot, block = [], [], None, None
    for number, line in enumerate(text.splitlines(), 1):
        stripped = line.strip()
        if block is not None:
            kept.append(line)
            if stripped == f"</{block}>":
                block = None
            elif not BLOCK_BODY_RE.fullmatch(stripped):
                raise GenerationError(f"{source}:{number}: unexpected line in <{block}> block")
            continue
        if not stripped or stripped[0] in "#;":
            kept.append(line)
            continue
        match = BLOCK_RE.match(stripped)
        if match:
            if match.group(1) or match.group(2) not in ALLOWED_BLOCKS:
                raise GenerationError(f"{source}:{number}: unexpected block {stripped!r}")
            block = match.group(2)
            kept.append(line)
            continue
        tokens = stripped.split()
        if tokens[0] not in ALLOWED_DIRECTIVES:
            raise GenerationError(
                f"{source}:{number}: directive {tokens[0]!r} is not allowlisted; "
                "review it and add it to ALLOWED_DIRECTIVES if it is safe"
            )
        if tokens[0] == "remote-random":
            continue  # meaningless with a single remote
        if tokens[0] == "remote":
            if len(tokens) < 2 or not HOSTNAME_RE.match(tokens[1]):
                raise GenerationError(f"{source}:{number}: malformed remote line")
            if slot is None:
                slot = len(kept)
            remotes.append(tokens[1].lower())
            continue
        kept.append(line)
    if block is not None:
        raise GenerationError(f"{source}: unterminated <{block}> block")
    if not remotes:
        raise GenerationError(f"{source}: no remote lines")
    return kept, remotes, slot


def safe_name(text):
    """ASCII, no spaces. The endpoint stats file is space-separated and keyed on
    the basename, and IVPN ships names such as Mexico-Querétaro.ovpn."""
    ascii_text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return re.sub(r"[^A-Za-z0-9_-]", "_", ascii_text)


def build_configs(zip_bytes, hosts, port, countries=None):
    """Return {filename: contents}, one per server. The archive is only read in
    memory, never extracted, and output names are rebuilt rather than trusted."""
    try:
        archive = zipfile.ZipFile(io.BytesIO(zip_bytes))
    except zipfile.BadZipFile as exc:
        raise GenerationError(f"IVPN did not return a valid zip: {exc}") from exc

    configs = {}
    with archive:
        for entry in sorted(archive.namelist()):
            if not entry.endswith(".ovpn"):
                continue
            stem = os.path.basename(entry)[: -len(".ovpn")]
            if archive.getinfo(entry).file_size > MAX_DOWNLOAD_BYTES:
                raise GenerationError(f"{entry}: larger than {MAX_DOWNLOAD_BYTES} bytes unpacked")
            try:
                text = archive.read(entry).decode("utf-8")
            except UnicodeDecodeError as exc:
                raise GenerationError(f"{entry}: not valid UTF-8") from exc
            except (zipfile.BadZipFile, zlib.error, RuntimeError) as exc:
                raise GenerationError(f"{entry}: could not read from the zip: {exc}") from exc
            lines, remotes, slot = parse_template(entry, text)
            for hostname in remotes:
                if hostname not in hosts:
                    warn(f"{entry}: {hostname} is not in the server list; skipped")
                    continue
                ip, country = hosts[hostname]
                if countries and country not in countries:
                    continue
                name = f"{safe_name(stem)}-{safe_name(hostname.split('.')[0])}.ovpn"
                if name in configs:
                    raise GenerationError(f"two servers map to the filename {name}")
                body = [*lines[:slot], f"remote {ip} {port}", *lines[slot:]]
                header = [MARKER, f"# Server: {hostname}"]
                configs[name] = "\n".join(header + body) + "\n"
    return configs


def is_generated(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as handle:
            return handle.readline().rstrip("\n") == MARKER
    except OSError:
        return False


def write_configs(configs, output_dir):
    """Write the new set, then prune generated files it no longer includes.

    Anything this script did not write is left alone, so pointing --output at a
    directory of hand-downloaded configs cannot destroy them.
    """
    if not configs:
        raise GenerationError("nothing to write: no servers matched")
    os.makedirs(output_dir, exist_ok=True)

    existing = [n for n in os.listdir(output_dir) if n.endswith(".ovpn")]
    foreign = [n for n in existing if not is_generated(os.path.join(output_dir, n))]
    clashes = sorted(set(foreign) & set(configs))
    if clashes:
        raise GenerationError(f"refusing to overwrite files not generated here: {clashes}")
    for name in foreign:
        warn(f"{name} is not generated by this script but will still be in the rotation")

    for name, body in configs.items():
        descriptor, temporary = tempfile.mkstemp(dir=output_dir, prefix=".tmp-")
        try:
            with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
                handle.write(body)
            os.chmod(temporary, 0o644)
            os.replace(temporary, os.path.join(output_dir, name))
        except BaseException:
            if os.path.exists(temporary):
                os.unlink(temporary)
            raise

    removed = sorted(set(existing) - set(foreign) - set(configs))
    for name in removed:
        os.unlink(os.path.join(output_dir, name))
    return removed


def parse_args(argv):
    parser = argparse.ArgumentParser(
        description="Generate one IP-based .ovpn file per IVPN server."
    )
    parser.add_argument(
        "--country",
        default="",
        help="comma-separated country codes to keep, e.g. NL,DE,CH (default: all)",
    )
    parser.add_argument("--proto", choices=sorted(DEFAULT_PORTS), default="udp")
    parser.add_argument(
        "--port", type=int, help="default: 2049 for udp, 443 for tcp"
    )
    parser.add_argument(
        "--output", default=DEFAULT_OUTPUT, help="default: ovpn_configs_ivpn/ in this repo"
    )
    return parser.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)
    port = args.port if args.port is not None else DEFAULT_PORTS[args.proto]
    countries = {c.strip().upper() for c in args.country.split(",") if c.strip()}

    try:
        servers = json.loads(fetch(SERVERS_URL))
        check_port(servers, args.proto, port)
        hosts = index_hosts(servers)

        unknown = sorted(countries - {country for _, country in hosts.values()})
        if unknown:
            raise GenerationError(f"no IVPN servers in country code(s): {unknown}")

        query = urllib.parse.urlencode({"proto": args.proto, "port": port})
        configs = build_configs(fetch(f"{CONFIG_URL}?{query}"), hosts, port, countries)
        removed = write_configs(configs, args.output)
    except (GenerationError, OSError, ValueError, KeyError, TypeError, AttributeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    print(f"Wrote {len(configs)} configs to {args.output}; pruned {len(removed)} stale.")
    if len(configs) > LARGE_FLEET:
        warn(
            f"{len(configs)} exits is a large fleet: at the default daily rotation "
            "one full pass takes months. Consider narrowing it with --country."
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
